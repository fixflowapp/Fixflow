#!/usr/bin/env node
// FixFlow replica — one-shot Supabase setup.
//
// Usage:
//   SUPABASE_PAT=sbp_xxx SUPABASE_SERVICE_KEY=eyJ... node supabase/setup.mjs
//
// Steps:
//   1. Apply supabase/schema.sql via the Management API (needs a personal access token)
//   2. Fetch the project's anon public key
//   3. Write app/js/supabase-config.js (url + anonKey)
//   4. Seed all collections from supabase/seed.json (needs the service_role key)
//   5. Verify persisted counts
//
// Secrets are read from the environment only — never written to disk.

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const __dir = dirname(fileURLToPath(import.meta.url));
const PAT = process.env.SUPABASE_PAT;
const SVC = process.env.SUPABASE_SERVICE_KEY;
if (!PAT || !SVC) { console.error("Missing SUPABASE_PAT and/or SUPABASE_SERVICE_KEY"); process.exit(1); }

const decode = (jwt) => JSON.parse(Buffer.from(jwt.split(".")[1], "base64url").toString());
const REF = process.env.SUPABASE_REF || decode(SVC).ref;
const BASE = `https://${REF}.supabase.co`;
const MGMT = "https://api.supabase.com/v1";
console.log(`Project ref: ${REF}\nProject URL: ${BASE}\n`);

const j = (r) => r.json().catch(() => ({}));

// 1. Schema -----------------------------------------------------------------
const sql = readFileSync(resolve(__dir, "schema.sql"), "utf8");
process.stdout.write("Applying schema.sql ... ");
const schemaRes = await fetch(`${MGMT}/projects/${REF}/database/query`, {
  method: "POST",
  headers: { Authorization: `Bearer ${PAT}`, "Content-Type": "application/json" },
  body: JSON.stringify({ query: sql }),
});
if (!schemaRes.ok) { console.error(`\n  FAILED ${schemaRes.status}:`, await j(schemaRes)); process.exit(1); }
console.log("ok");

// 2. Anon key ---------------------------------------------------------------
process.stdout.write("Fetching anon key ... ");
const keysRes = await fetch(`${MGMT}/projects/${REF}/api-keys?reveal=true`, { headers: { Authorization: `Bearer ${PAT}` } });
const keys = await j(keysRes);
const anon = (Array.isArray(keys) ? keys : []).find((k) => k.name === "anon")?.api_key;
if (!anon) { console.error("\n  could not find anon key:", keys); process.exit(1); }
console.log(`ok (${anon.slice(0, 12)}…)`);

// 3. Config -----------------------------------------------------------------
const cfgPath = resolve(__dir, "../app/js/supabase-config.js");
writeFileSync(cfgPath, `// FixFlow replica — Supabase configuration (generated by supabase/setup.mjs)
window.FIXFLOW_SUPABASE = {
  url: "${BASE}",
  anonKey: "${anon}",
};
`);
console.log("Wrote app/js/supabase-config.js");

// 4. Seed -------------------------------------------------------------------
const seed = JSON.parse(readFileSync(resolve(__dir, "seed.json"), "utf8"));
const COLLECTIONS = ["technicians", "customers", "jobs", "invoices", "payments", "suppliers", "parts",
  "contracts", "workOrders", "templates", "recurringJobs", "assets", "conversations",
  "auditLogs", "gdprRequests", "notifications", "serviceRequests"];

const H = { apikey: SVC, Authorization: `Bearer ${SVC}`, "Content-Type": "application/json" };
const chunk = (a, n) => a.reduce((out, x, i) => (i % n ? out : [...out, a.slice(i, i + n)]), []);

for (const name of COLLECTIONS) {
  const rows = seed[name] || [];
  process.stdout.write(`  ${name.padEnd(16)} `);
  await fetch(`${BASE}/rest/v1/ff_records?collection=eq.${name}`, { method: "DELETE", headers: H });
  if (rows.length) {
    const payload = rows.map((r) => ({ collection: name, id: String(r.id), data: r }));
    for (const part of chunk(payload, 200)) {
      const res = await fetch(`${BASE}/rest/v1/ff_records`, { method: "POST", headers: { ...H, Prefer: "return=minimal" }, body: JSON.stringify(part) });
      if (!res.ok) { console.error(`\n  FAILED ${res.status}:`, await j(res)); process.exit(1); }
    }
  }
  console.log(`${rows.length} rows`);
}

process.stdout.write(`  ${"settings".padEnd(16)} `);
await fetch(`${BASE}/rest/v1/ff_settings?id=eq.default`, { method: "DELETE", headers: H });
const sres = await fetch(`${BASE}/rest/v1/ff_settings`, { method: "POST", headers: { ...H, Prefer: "return=minimal" }, body: JSON.stringify({ id: "default", data: seed.settings }) });
console.log(sres.ok ? "saved" : `FAILED ${sres.status}`);

// 5. Verify -----------------------------------------------------------------
process.stdout.write("\nVerifying ... ");
const vres = await fetch(`${BASE}/rest/v1/ff_records?select=collection`, { headers: H });
const all = await j(vres);
const counts = all.reduce((m, r) => ((m[r.collection] = (m[r.collection] || 0) + 1), m), {});
console.log(`${all.length} rows total`);
console.log(Object.entries(counts).map(([k, v]) => `  ${k}: ${v}`).join("\n"));
console.log(`\nDone. Open the app — Settings → Advanced shows "Supabase" when connected.`);
